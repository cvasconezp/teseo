console.log("WMM2025: valores de prueba oficiales (100 puntos, 2025.0 a 2029.5)");
{
  let wD = 0, wI = 0, wXYZ = 0, wF = 0, bad = [];
  for (const [yr, alt, lat, lon, D, I, Hh, X, Y, Z, F] of OFFICIAL) {
    const f = magneticField(lat, lon, alt, yr);
    const eD = angDiff(f.decl, D), eI = Math.abs(f.incl - I);
    const eC = Math.max(Math.abs(f.x - X), Math.abs(f.y - Y), Math.abs(f.z - Z), Math.abs(f.h - Hh));
    wD = Math.max(wD, eD); wI = Math.max(wI, eI); wXYZ = Math.max(wXYZ, eC); wF = Math.max(wF, Math.abs(f.f - F));
    if (eD > 0.0051 || eI > 0.0051 || eC > 0.05) bad.push([yr, lat, lon, eD, eI, eC]);
  }
  ok(OFFICIAL.length === 100, "se comprueban los 100 puntos oficiales");
  ok(wD <= 0.0051, "declinación: coincide con los 2 decimales publicados", `error máx ${wD.toFixed(5)}°`);
  ok(wI <= 0.0051, "inclinación: coincide con los 2 decimales publicados", `error máx ${wI.toFixed(5)}°`);
  ok(wXYZ <= 0.05, "componentes X, Y, Z y H dentro de 0,05 nT", `error máx ${wXYZ.toFixed(4)} nT`);
  ok(wF <= 0.05, "intensidad total F dentro de 0,05 nT", `error máx ${wF.toFixed(4)} nT`);
  ok(bad.length === 0, "ningún punto fuera de tolerancia", JSON.stringify(bad.slice(0, 3)));
  console.log(`        errores máximos: D ${wD.toExponential(2)}°, I ${wI.toExponential(2)}°, XYZ ${wXYZ.toExponential(2)} nT, F ${wF.toExponential(2)} nT`);
}

